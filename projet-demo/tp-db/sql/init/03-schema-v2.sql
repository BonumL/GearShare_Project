CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE avis (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    reservation_id INTEGER NOT NULL,
    note SMALLINT NOT NULL,
    commentaire TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT avis_pkey PRIMARY KEY (id),
    CONSTRAINT avis_reservation_id_unique UNIQUE (reservation_id),
    CONSTRAINT avis_reservation_id_fkey
        FOREIGN KEY (reservation_id)
        REFERENCES reservations(id)
        ON DELETE CASCADE,
    CONSTRAINT avis_note_valide
        CHECK (note BETWEEN 1 AND 5)
);

CREATE TABLE tags (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    libelle VARCHAR(50) NOT NULL,
    CONSTRAINT tags_pkey PRIMARY KEY (id),
    CONSTRAINT tags_libelle_unique UNIQUE (libelle),
    CONSTRAINT tags_libelle_minuscule
        CHECK (libelle = lower(libelle))
);

CREATE TABLE item_tags (
    item_id INTEGER NOT NULL,
    tag_id INTEGER NOT NULL,
    CONSTRAINT item_tags_pkey PRIMARY KEY (item_id, tag_id),
    CONSTRAINT item_tags_item_id_fkey
        FOREIGN KEY (item_id)
        REFERENCES items(id)
        ON DELETE CASCADE,
    CONSTRAINT item_tags_tag_id_fkey
        FOREIGN KEY (tag_id)
        REFERENCES tags(id)
        ON DELETE CASCADE
);

ALTER TABLE reservations
    DROP CONSTRAINT IF EXISTS reservations_borrower_id_fkey;

ALTER TABLE reservations
    ADD CONSTRAINT reservations_borrower_id_fkey
    FOREIGN KEY (borrower_id)
    REFERENCES users(id)
    ON DELETE NO ACTION;

ALTER TABLE reservations
    ADD CONSTRAINT reservations_no_active_overlap
    EXCLUDE USING gist (
        item_id WITH =,
        daterange(date_debut, date_fin, '[)') WITH &&
    )
    WHERE (statut = 'active');

CREATE INDEX idx_items_owner_id
    ON items (owner_id);

CREATE INDEX idx_reservations_item_id
    ON reservations (item_id);

CREATE INDEX idx_reservations_borrower_id
    ON reservations (borrower_id);

CREATE INDEX idx_item_tags_tag_id
    ON item_tags (tag_id);

CREATE OR REPLACE FUNCTION verifier_avis_reservation_terminee()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    reservation_statut VARCHAR(8);
BEGIN
    SELECT statut
    INTO reservation_statut
    FROM reservations
    WHERE id = NEW.reservation_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RETURN NEW;
    END IF;

    IF reservation_statut <> 'terminee' THEN
        RAISE EXCEPTION USING
            ERRCODE = '23514',
            CONSTRAINT = 'avis_reservation_terminee',
            MESSAGE = 'Un avis ne peut concerner qu''une réservation terminée';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER avis_reservation_terminee
    BEFORE INSERT OR UPDATE ON avis
    FOR EACH ROW
    EXECUTE FUNCTION verifier_avis_reservation_terminee();
